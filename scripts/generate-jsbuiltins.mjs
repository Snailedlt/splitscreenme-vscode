// data/js-builtins.json: JavaScript's own ES5 objects and methods (String, Array, Math, JSON, Number, the global
// functions) with their parameters and docs, taken from TypeScript's lib.es5.d.ts. ES5 is what Jint 2.11.58 has.
// Used for suggestions, hover and parameter hints after a string, an array, `Math.`, `JSON.` (core/jsbuiltins.ts),
// and to flag a misspelled one. Run: node scripts/generate-jsbuiltins.mjs (part of npm run generate; a test checks
// the committed file matches).
import fs from 'node:fs';
import ts from 'typescript';

const LIB = new URL('../node_modules/typescript/lib/lib.es5.d.ts', import.meta.url);
const OUT = new URL('../data/js-builtins.json', import.meta.url);

/** Our object name -> the interfaces it is made of. */
const OBJECTS = { String: ['String'], Array: ['Array'], Math: ['Math'], JSON: ['JSON'], Number: ['Number'] };
const GLOBAL_FUNCTIONS = ['parseInt', 'parseFloat', 'isNaN', 'isFinite', 'encodeURIComponent', 'decodeURIComponent', 'encodeURI', 'decodeURI'];
// Not useful in handlers, or not in Jint's ES5 runtime the way TypeScript describes it.
const SKIP = new Set(['toLocaleString', 'toLocaleLowerCase', 'toLocaleUpperCase', 'localeCompare', 'valueOf', '__index']);

export function generate() {
  const src = ts.createSourceFile('lib.es5.d.ts', fs.readFileSync(LIB, 'utf8'), ts.ScriptTarget.ES5, true);
  const text = (n) => (n ? n.getText(src).replace(/\s+/g, ' ') : 'any');
  // Generic T, U, S: shown as "any" (handlers have no types).
  const plain = (t) =>
    t
      .replace(/\bthis: [^,)]+(, )?/g, '') // a callback's `this` type
      .replace(/\b[TUS]\b(\[\])?/g, (_, arr) => (arr ? 'any[]' : 'any'))
      .replace(/ReadonlyArray<any>/g, 'any[]')
      .replace(/ConcatArray<any>/g, 'any[]')
      .replace(/\bthis\b/g, 'any');
  // TypeScript-only overloads (type guards like `value is S`) mean nothing in a handler.
  const typeOnly = (m) => /\bis\b/.test(text(m.type)) || m.parameters.some((p) => /\bis\b/.test(text(p.type)));
  const docOf = (n) => {
    const d = (n.jsDoc ?? []).map((j) => (typeof j.comment === 'string' ? j.comment : (j.comment ?? []).map((c) => c.text).join(''))).join('\n').trim();
    const params = {};
    for (const j of n.jsDoc ?? []) for (const tag of j.tags ?? []) if (ts.isJSDocParameterTag(tag)) params[tag.name.getText(src)] = typeof tag.comment === 'string' ? tag.comment : (tag.comment ?? []).map((c) => c.text).join('');
    return { doc: d, params };
  };
  const params = (sig) =>
    sig.parameters.map((p) => ({
      name: p.name.getText(src),
      type: plain(text(p.type)),
      ...(p.questionToken ? { optional: true } : {}),
      ...(p.dotDotDotToken ? { rest: true } : {}),
    }));

  const objects = {};
  for (const [name, ifaces] of Object.entries(OBJECTS)) {
    const members = Object.create(null);
    ts.forEachChild(src, (node) => {
      if (!ts.isInterfaceDeclaration(node) || !ifaces.includes(node.name.text)) return;
      for (const m of node.members) {
        if (!m.name || SKIP.has(m.name.getText(src)) || ts.isIndexSignatureDeclaration(m)) continue;
        const key = m.name.getText(src);
        const { doc } = docOf(m);
        if (ts.isMethodSignature(m)) {
          if (typeOnly(m)) continue;
          const prev = Object.hasOwn(members, key) ? members[key] : undefined;
          const ov = { returns: plain(text(m.type)), params: params(m) };
          if (prev) prev.overloads.push(ov);
          else members[key] = { kind: 'method', doc, overloads: [ov] };
        } else if (ts.isPropertySignature(m)) {
          members[key] = { kind: 'property', type: plain(text(m.type)), ts: plain(text(m.type)), readonly: !!m.modifiers?.some((x) => x.kind === ts.SyntaxKind.ReadonlyKeyword), doc };
        }
      }
    });
    objects[name] = { doc: `JavaScript's ${name} (ES5, as Jint runs it).`, members: Object.fromEntries(Object.entries(members).sort(([a], [b]) => a.localeCompare(b))) };
  }
  const functions = {};
  ts.forEachChild(src, (node) => {
    if (ts.isFunctionDeclaration(node) && node.name && GLOBAL_FUNCTIONS.includes(node.name.text)) {
      functions[node.name.text] = { kind: 'method', doc: docOf(node).doc, overloads: [{ returns: plain(text(node.type)), params: params(node) }] };
    }
  });
  return { $comment: 'Generated by scripts/generate-jsbuiltins.mjs from TypeScript\'s lib.es5.d.ts. Do not edit by hand.', typescript: ts.version, objects, functions };
}

if (process.argv[1] && new URL(import.meta.url).pathname === fs.realpathSync(process.argv[1])) {
  const out = JSON.stringify(generate(), null, 1) + '\n';
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(OUT, 'utf8') !== out) {
      console.error('data/js-builtins.json is stale: run node scripts/generate-jsbuiltins.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`Wrote ${OUT.pathname}`);
  }
}
